"""
run_eq3.py — Regenerates every EQ3 number reported in the paper from the frozen inputs.

    python benchmark_evaluation/freeze_eq3.py   # verifies (or once creates) the frozen manifests
    python benchmark_evaluation/run_eq3.py

All definitions live in common/eq3_metrics.py and are identical for both domains.

Outputs (benchmark_evaluation/results/):
    eq3_transformation.csv, eq3_downstream.csv            Software Ethics
    eq3_bio_transformation.csv, eq3_bio_downstream.csv    Biomedical Native-BEL
    eq3_summary.json                                      everything above plus frozen manifests
    eq3_tables.tex                                        LaTeX rows for the paper tables
"""

import csv
import json
import sys
from pathlib import Path

BENCH_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(BENCH_DIR.parent))

from benchmark_evaluation.common.eq3_metrics import run_domain  # noqa: E402

RESULTS = BENCH_DIR / "results"
DOMAINS = [
    ("eq3_software_ethics", "Software Ethics", "eq3_transformation.csv", "eq3_downstream.csv"),
    ("eq3_biomedical_bel", "Biomedical BEL", "eq3_bio_transformation.csv", "eq3_bio_downstream.csv"),
]


def pct(num: int, den: int) -> str:
    return f"{100.0 * num / den:.1f}\\%" if den else "--"


def write_csv(path: Path, rows) -> None:
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        for r in rows:
            w.writerow({k: (round(v, 4) if isinstance(v, float) else v) for k, v in r.items()})


def main() -> None:
    RESULTS.mkdir(exist_ok=True)
    summary = {}
    tex = ["% Generated by benchmark_evaluation/run_eq3.py -- do not edit by hand."]

    for dir_name, label, t_csv, d_csv in DOMAINS:
        res = run_domain(BENCH_DIR / dir_name)
        summary[dir_name] = res
        write_csv(RESULTS / t_csv, res["transformation"])
        write_csv(RESULTS / d_csv, res["downstream"])

        n_ref = res["transformation"][0]["n_reference"]
        tex.append(f"% ---- {label}: candidate-to-reference alignment ({res['n_sentences']} sentences, |B1| = {n_ref})")
        tex.append("% Source & |C| & Exact & Near miss & Unaligned & B1 found exactly & B1 with no counterpart")
        for t in res["transformation"]:
            n = t["n_candidates"]
            tex.append(
                f"{t['source']} & {n} & {t['exact']} ({pct(t['exact'], n)}) & {t['near_miss']} ({pct(t['near_miss'], n)}) & "
                f"{t['unaligned']} ({pct(t['unaligned'], n)}) & {t['ref_exact_covered']} ({pct(t['ref_exact_covered'], n_ref)}) & "
                f"{t['ref_uncovered']} ({pct(t['ref_uncovered'], n_ref)}) \\\\"
            )
        tex.append(f"% ---- {label}: downstream scores (F1 vs B0; P/R/F1 vs leave-one-out pool and vs B1; F1(B1) - F1(pool) in pp)")
        for d in res["downstream"]:
            tex.append(
                f"& {d['system']} & {100*d['b0_f1']:.1f} & "
                f"{100*d['loo_p']:.1f} & {100*d['loo_r']:.1f} & {100*d['loo_f1']:.1f} & "
                f"{100*d['b1_p']:.1f} & {100*d['b1_r']:.1f} & {100*d['b1_f1']:.1f} & "
                f"${100*d['delta_f1_loo']:+.1f}$ [{100*d['ci_loo_lower']:+.1f}, {100*d['ci_loo_upper']:+.1f}] \\\\"
            )

    with open(RESULTS / "eq3_summary.json", "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)
    (RESULTS / "eq3_tables.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")
    print("\n".join(tex))


if __name__ == "__main__":
    main()

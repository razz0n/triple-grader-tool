"""
run_eq3.py: regenerates the EQ3 table (Table III of the paper) from the curated sessions.

    python benchmark_evaluation/freeze_eq3.py   # checks the frozen inputs
    python benchmark_evaluation/run_eq3.py

For every model it counts the candidates kept unchanged (exact), kept with a corrected slot
(modified), removed (deleted) and the triples added during curation (newly suggested); see
common/eq3_curation.py for the definitions. It also checks that each published version equals B1.

Outputs (benchmark_evaluation/results/):
    eq3_curation.csv     one row per corpus and model
    eq3_summary.json     the same counts with the frozen-input manifests
    eq3_tables.tex       LaTeX rows for Table III
"""

import csv
import json
import sys
from pathlib import Path

BENCH_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(BENCH_DIR.parent))

from benchmark_evaluation.common.eq3_curation import (  # noqa: E402
    B1_FILE, MODELS, candidates_file, curation_outcomes, load_json, matches_benchmark,
    original_candidates, published_sentences, session_file,
)
from benchmark_evaluation.freeze_eq3 import check as check_frozen  # noqa: E402

RESULTS = BENCH_DIR / "results"
DOMAINS = [("eq3_software_ethics", "Software ethics"), ("eq3_biomedical_bel", "Biomedical BEL")]


def pct(num: int, den: int) -> str:
    return f"{100.0 * num / den:.1f}"


def run_domain(dir_name: str, label: str) -> list:
    exp = BENCH_DIR / dir_name
    b1 = load_json(exp / B1_FILE)
    b1_size = sum(len(s["triples"]) for s in b1["sentences"])
    rows = []
    for model, stem in MODELS:
        frozen = load_json(exp / candidates_file(stem))
        order = [s["sentence_id"] for s in frozen["versions"][0]["sentences"]]
        published = published_sentences(load_json(exp / session_file(stem)))
        counts = curation_outcomes(original_candidates(frozen), published)
        differ = matches_benchmark(published, b1, order)
        if differ:
            raise SystemExit(f"[{dir_name}] {model}: published version differs from B1 in sentences {differ}")
        if counts["exact"] + counts["modified"] + counts["new"] != b1_size:
            raise SystemExit(f"[{dir_name}] {model}: exact + modified + new does not equal |B1| = {b1_size}")
        n = counts["candidates"]
        rows.append({
            "corpus": label, "model": model, "b1_triples": b1_size, "candidates": n,
            "exact": counts["exact"], "exact_pct": pct(counts["exact"], n),
            "modified": counts["modified"], "modified_pct": pct(counts["modified"], n),
            "deleted": counts["deleted"], "deleted_pct": pct(counts["deleted"], n),
            "newly_suggested": counts["new"], "newly_suggested_pct_of_b1": pct(counts["new"], b1_size),
        })
    return rows


def latex_rows(rows: list) -> str:
    lines = []
    for i, r in enumerate(rows):
        first = i % len(MODELS) == 0
        corpus = r["corpus"] if first else ("($|B_1| = " + str(r["b1_triples"]) + "$)" if i % len(MODELS) == 1 else "")
        if first and i:
            lines.append("\\midrule")
        lines.append(
            f"{corpus} & {r['model']} & {r['candidates']} & {r['exact']} ({r['exact_pct']}\\%) & "
            f"{r['modified']} ({r['modified_pct']}\\%) & {r['deleted']} ({r['deleted_pct']}\\%) & "
            f"{r['newly_suggested']} ({r['newly_suggested_pct_of_b1']}\\%) \\\\")
    return "\n".join(lines) + "\n"


def main() -> None:
    RESULTS.mkdir(parents=True, exist_ok=True)
    manifests = {dir_name: check_frozen(dir_name) for dir_name, _ in DOMAINS}
    rows = [row for dir_name, label in DOMAINS for row in run_domain(dir_name, label)]
    with open(RESULTS / "eq3_curation.csv", "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    with open(RESULTS / "eq3_summary.json", "w", encoding="utf-8", newline="\n") as f:
        json.dump({"table_iii": rows, "frozen_inputs": manifests}, f, indent=2, ensure_ascii=False)
        f.write("\n")
    with open(RESULTS / "eq3_tables.tex", "w", encoding="utf-8", newline="\n") as f:
        f.write("% Table III rows, generated by benchmark_evaluation/run_eq3.py\n" + latex_rows(rows))
    for r in rows:
        print(f"  {r['corpus']:15} {r['model']:17} candidates {r['candidates']:3}  exact {r['exact']:3}  "
              f"modified {r['modified']:3}  deleted {r['deleted']:3}  newly suggested {r['newly_suggested']:3}")


if __name__ == "__main__":
    main()

"""
Transformation metrics analysis for Biomedical Native-BEL candidate sets.

Computes exact candidate retention, modification, removal, and curation intensity
for candidate sets generated by ChatGPT-5.6-High, Gemini-3.1-Pro, GPT-OSS 120B,
and Qwen 3.8 27B, as well as the uncurated candidate union (B0) against the curated
gold benchmark (B1).
"""

import csv
import json
from pathlib import Path
from typing import Any, Dict, List

ROOT_DIR = Path(__file__).resolve().parent.parent.parent
EXP_DIR = Path(__file__).resolve().parent
CAND_DIR = EXP_DIR / "candidates"
RESULTS_DIR = ROOT_DIR / "benchmark_evaluation" / "results"
RESULTS_DIR.mkdir(parents=True, exist_ok=True)

TOTAL_GOLD_RELATIONS = 69


def norm(s: str) -> str:
    return str(s or "").strip().lower().replace("_", "").replace("-", "").replace('"', "")


def build_ledger_from_session(session_path: Path, source_name: str) -> Dict[str, Any]:
    with open(session_path, "r", encoding="utf-8") as f:
        session = json.load(f)

    versions = session.get("versions", [])
    if len(versions) < 2:
        raise ValueError(f"Session {session_path} requires initial and final versions")

    initial_sentences = versions[0]["sentences"]
    final_sentences = versions[-1]["sentences"]

    gold_by_sid = {s["sentence_id"]: s.get("triples", []) for s in final_sentences}

    outcome_counts = {
        "accepted_unchanged": 0,
        "accepted_modified": 0,
        "removed_rejected": 0,
    }

    covered_gold_ids = set()
    total_candidates = 0

    for s in initial_sentences:
        sid = s["sentence_id"]
        c_triples = s.get("triples", [])
        g_triples = gold_by_sid.get(sid, [])
        total_candidates += len(c_triples)

        matched_g = set()
        for t in c_triples:
            # Check exact match against gold relations
            exact_g = None
            for g_idx, gt in enumerate(g_triples):
                if g_idx not in matched_g:
                    if (norm(gt["subject"]) == norm(t["subject"]) and
                        norm(gt["predicate"]) == norm(t["predicate"]) and
                        norm(gt["object"]) == norm(t["object"])):
                        exact_g = g_idx
                        break
            if exact_g is not None:
                matched_g.add(exact_g)
                outcome_counts["accepted_unchanged"] += 1
                covered_gold_ids.add(f"{sid}_{exact_g}")
            else:
                # Check partial alignment (modified during curation)
                near_g = None
                for g_idx, gt in enumerate(g_triples):
                    if g_idx not in matched_g:
                        if (norm(gt["predicate"]) == norm(t["predicate"]) or
                            norm(gt["subject"]) == norm(t["subject"])):
                            near_g = g_idx
                            break
                if near_g is not None:
                    matched_g.add(near_g)
                    outcome_counts["accepted_modified"] += 1
                    covered_gold_ids.add(f"{sid}_{near_g}")
                else:
                    outcome_counts["removed_rejected"] += 1

    gap_additions = TOTAL_GOLD_RELATIONS - len(covered_gold_ids)
    retention_rate = outcome_counts["accepted_unchanged"] / total_candidates if total_candidates > 0 else 0.0
    mod_rate = outcome_counts["accepted_modified"] / total_candidates if total_candidates > 0 else 0.0
    removal_rate = outcome_counts["removed_rejected"] / total_candidates if total_candidates > 0 else 0.0
    precision_exact = outcome_counts["accepted_unchanged"] / total_candidates if total_candidates > 0 else 0.0
    recall_exact = len(covered_gold_ids) / TOTAL_GOLD_RELATIONS if TOTAL_GOLD_RELATIONS > 0 else 0.0
    curation_intensity = (outcome_counts["accepted_modified"] + outcome_counts["removed_rejected"] + gap_additions) / TOTAL_GOLD_RELATIONS

    return {
        "source_system": source_name,
        "total_candidates": total_candidates,
        "accepted_unchanged": outcome_counts["accepted_unchanged"],
        "accepted_modified": outcome_counts["accepted_modified"],
        "removed_rejected": outcome_counts["removed_rejected"],
        "gap_additions": gap_additions,
        "retention_rate": retention_rate,
        "modification_rate": mod_rate,
        "removal_rate": removal_rate,
        "precision_exact": precision_exact,
        "recall_exact": recall_exact,
        "curation_intensity": curation_intensity,
    }


def build_b0_union_metrics(session_paths: List[Path]) -> Dict[str, Any]:
    sessions = []
    for sp in session_paths:
        with open(sp, "r", encoding="utf-8") as f:
            sessions.append(json.load(f))

    final_sentences = sessions[0]["versions"][-1]["sentences"]
    gold_by_sid = {s["sentence_id"]: s.get("triples", []) for s in final_sentences}

    outcome_counts = {
        "accepted_unchanged": 0,
        "accepted_modified": 0,
        "removed_rejected": 0,
    }

    covered_gold_ids = set()
    total_candidates = 0

    for idx, s in enumerate(sessions[0]["versions"][0]["sentences"]):
        sid = s["sentence_id"]
        seen_triples = set()
        c_triples = []
        for sess in sessions:
            for t in sess["versions"][0]["sentences"][idx].get("triples", []):
                tup = (norm(t["subject"]), norm(t["predicate"]), norm(t["object"]))
                if tup not in seen_triples and tup != ("", "", ""):
                    seen_triples.add(tup)
                    c_triples.append(t)

        total_candidates += len(c_triples)
        g_triples = gold_by_sid.get(sid, [])
        matched_g = set()

        for t in c_triples:
            exact_g = None
            for g_idx, gt in enumerate(g_triples):
                if g_idx not in matched_g:
                    if (norm(gt["subject"]) == norm(t["subject"]) and
                        norm(gt["predicate"]) == norm(t["predicate"]) and
                        norm(gt["object"]) == norm(t["object"])):
                        exact_g = g_idx
                        break
            if exact_g is not None:
                matched_g.add(exact_g)
                outcome_counts["accepted_unchanged"] += 1
                covered_gold_ids.add(f"{sid}_{exact_g}")
            else:
                near_g = None
                for g_idx, gt in enumerate(g_triples):
                    if g_idx not in matched_g:
                        if (norm(gt["predicate"]) == norm(t["predicate"]) or
                            norm(gt["subject"]) == norm(t["subject"])):
                            near_g = g_idx
                            break
                if near_g is not None:
                    matched_g.add(near_g)
                    outcome_counts["accepted_modified"] += 1
                    covered_gold_ids.add(f"{sid}_{near_g}")
                else:
                    outcome_counts["removed_rejected"] += 1

    gap_additions = TOTAL_GOLD_RELATIONS - len(covered_gold_ids)
    retention_rate = outcome_counts["accepted_unchanged"] / total_candidates if total_candidates > 0 else 0.0
    mod_rate = outcome_counts["accepted_modified"] / total_candidates if total_candidates > 0 else 0.0
    removal_rate = outcome_counts["removed_rejected"] / total_candidates if total_candidates > 0 else 0.0
    precision_exact = outcome_counts["accepted_unchanged"] / total_candidates if total_candidates > 0 else 0.0
    recall_exact = len(covered_gold_ids) / TOTAL_GOLD_RELATIONS if TOTAL_GOLD_RELATIONS > 0 else 0.0
    curation_intensity = (outcome_counts["accepted_modified"] + outcome_counts["removed_rejected"] + gap_additions) / TOTAL_GOLD_RELATIONS

    return {
        "source_system": "B0_Raw_PreCuration_Union",
        "total_candidates": total_candidates,
        "accepted_unchanged": outcome_counts["accepted_unchanged"],
        "accepted_modified": outcome_counts["accepted_modified"],
        "removed_rejected": outcome_counts["removed_rejected"],
        "gap_additions": gap_additions,
        "retention_rate": retention_rate,
        "modification_rate": mod_rate,
        "removal_rate": removal_rate,
        "precision_exact": precision_exact,
        "recall_exact": recall_exact,
        "curation_intensity": curation_intensity,
    }


def main():
    sources = [
        ("C1_ChatGPT_5_6_High", CAND_DIR / "candidates_chatgpt_5_6_high_sentences.json"),
        ("C2_Gemini_3_1_Pro", CAND_DIR / "candidates_gemini_3_1_pro_sentences.json"),
        ("C3_GPT_OSS_120B", CAND_DIR / "candidates_gpt_oss_120b_sentences.json"),
        ("C4_Qwen_38B", CAND_DIR / "candidates_qwen_38b_sentences.json"),
    ]

    records = []
    session_paths = []
    for name, p in sources:
        session_paths.append(p)
        rec = build_ledger_from_session(p, name)
        records.append(rec)

    b0_rec = build_b0_union_metrics(session_paths)
    records.append(b0_rec)

    csv_path = RESULTS_DIR / "eq3_bio_transformation.csv"
    with open(csv_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(records[0].keys()))
        writer.writeheader()
        writer.writerows(records)

    print(f"Saved transformation metrics to {csv_path}")


if __name__ == "__main__":
    main()
